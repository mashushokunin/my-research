function summary = exp01_orb_baseline()
%EXP01_ORB_BASELINE Run the first two-image ORB matching experiment.
%
% This experiment:
%   1. loads a configured image pair,
%   2. detects and describes ORB keypoints,
%   3. matches the binary descriptors,
%   4. saves a summary CSV and match visualization.
%
% If the configured local frames are unavailable, the experiment uses a
% Computer Vision Toolbox image pair as a smoke test. Results produced from
% that fallback pair must not be treated as research results.

experimentDir = string(fileparts(mfilename("fullpath")));
projectRoot = string(fileparts(experimentDir));
addpath(fullfile(projectRoot, "configs", "matlab"));
addpath(fullfile(projectRoot, "src", "features"));

checkRequiredFunctions();
config = experiment_config();
rng(config.randomSeed, "twister");

[image1, image2, inputInfo] = loadImagePair(config);

orb1 = extractORB(image1, config.orb);
orb2 = extractORB(image2, config.orb);
matches = matchORB(orb1, orb2, config.match);

if matches.count == 0
    error("myresearch:NoORBMatches", ...
        "No ORB matches were found. Adjust the image pair or match settings.");
end

outputDir = config.output.directory;
if ~isfolder(outputDir)
    mkdir(outputDir);
end

figurePath = fullfile(outputDir, config.output.figureFile);
saveMatchFigure(orb1, orb2, matches, config.visualization, figurePath);

summary = makeSummaryTable(config, inputInfo, image1, image2, ...
    orb1, orb2, matches, figurePath);
summaryPath = fullfile(outputDir, config.output.summaryFile);
writetable(summary, summaryPath);

fprintf("ORB baseline completed.\n");
fprintf("  input source: %s\n", inputInfo.source);
fprintf("  valid ORB points: %d / %d\n", orb1.validCount, orb2.validCount);
fprintf("  matches: %d\n", matches.count);
fprintf("  summary: %s\n", summaryPath);
fprintf("  figure: %s\n", figurePath);

if ~inputInfo.researchInput
    warning("myresearch:SmokeTestInput", ...
        "The configured research images were unavailable, so this run used " + ...
        "Computer Vision Toolbox sample images. Do not report this run as a " + ...
        "research result.");
end
end

function checkRequiredFunctions()
requiredFunctions = [ ...
    "detectORBFeatures"
    "extractFeatures"
    "matchFeatures"
    "showMatchedFeatures"
];

missing = false(size(requiredFunctions));
for index = 1:numel(requiredFunctions)
    missing(index) = isempty(which(requiredFunctions(index)));
end

if any(missing)
    error("myresearch:MissingComputerVisionToolbox", ...
        "Required MATLAB functions are unavailable: %s", ...
        strjoin(requiredFunctions(missing), ", "));
end
end

function [image1, image2, info] = loadImagePair(config)
path1 = string(config.input.image1);
path2 = string(config.input.image2);

if isfile(path1) && isfile(path2)
    source = "configured-research-pair";
    researchInput = true;
elseif config.input.allowBuiltInFallback
    path1 = string(which(config.input.fallbackImage1));
    path2 = string(which(config.input.fallbackImage2));
    source = "toolbox-smoke-test";
    researchInput = false;

    if strlength(path1) == 0 || strlength(path2) == 0
        error("myresearch:InputImagesNotFound", ...
            "Configured input images and built-in fallback images were not " + ...
            "found. Update configs/matlab/experiment_config.m.");
    end
else
    error("myresearch:InputImagesNotFound", ...
        "Configured input images were not found. Update " + ...
        "configs/matlab/experiment_config.m.");
end

image1 = imread(path1);
image2 = imread(path2);

file1 = dir(path1);
file2 = dir(path2);

info = struct;
info.source = source;
info.researchInput = researchInput;
info.path1 = path1;
info.path2 = path2;
info.fileBytes1 = file1.bytes;
info.fileBytes2 = file2.bytes;
end

function saveMatchFigure(orb1, orb2, matches, visualization, outputPath)
[~, order] = sort(double(matches.matchMetric), "ascend");
displayCount = min(matches.count, visualization.maxMatches);
displayIndices = order(1:displayCount);

points1 = matches.matchedPoints1(displayIndices);
points2 = matches.matchedPoints2(displayIndices);

figureHandle = figure( ...
    Name="Experiment 01: ORB baseline", ...
    Visible=visualization.visible);
showMatchedFeatures(orb1.grayImage, orb2.grayImage, ...
    points1, points2, "montage");
title(sprintf("Best %d of %d ORB matches", displayCount, matches.count));
legend("Image 1 points", "Image 2 points");
exportgraphics(figureHandle, outputPath);
end

function summary = makeSummaryTable(config, inputInfo, image1, image2, ...
        orb1, orb2, matches, figurePath)
timestampUtc = datetime("now", TimeZone="UTC", ...
    Format="yyyy-MM-dd'T'HH:mm:ssXXX");

summary = table( ...
    timestampUtc, ...
    inputInfo.source, ...
    inputInfo.researchInput, ...
    inputInfo.path1, ...
    inputInfo.path2, ...
    inputInfo.fileBytes1, ...
    inputInfo.fileBytes2, ...
    size(image1, 2), ...
    size(image1, 1), ...
    size(image2, 2), ...
    size(image2, 1), ...
    config.orb.maxPoints, ...
    config.orb.scaleFactor, ...
    config.orb.numLevels, ...
    orb1.detectedCount, ...
    orb2.detectedCount, ...
    orb1.validCount, ...
    orb2.validCount, ...
    orb1.descriptorBits, ...
    orb1.descriptorBytes, ...
    orb2.descriptorBytes, ...
    config.match.matchThreshold, ...
    config.match.maxRatio, ...
    config.match.unique, ...
    matches.count, ...
    matches.meanMetric, ...
    matches.medianMetric, ...
    orb1.elapsedMs, ...
    orb2.elapsedMs, ...
    matches.elapsedMs, ...
    string(figurePath), ...
    VariableNames=[ ...
        "timestamp_utc", ...
        "input_source", ...
        "research_input", ...
        "image1_path", ...
        "image2_path", ...
        "image1_file_bytes", ...
        "image2_file_bytes", ...
        "image1_width", ...
        "image1_height", ...
        "image2_width", ...
        "image2_height", ...
        "orb_max_points", ...
        "orb_scale_factor", ...
        "orb_num_levels", ...
        "detected_points1", ...
        "detected_points2", ...
        "valid_points1", ...
        "valid_points2", ...
        "descriptor_bits", ...
        "descriptor_bytes1", ...
        "descriptor_bytes2", ...
        "match_threshold", ...
        "max_ratio", ...
        "unique_matches", ...
        "num_matches", ...
        "mean_match_metric", ...
        "median_match_metric", ...
        "extraction_time1_ms", ...
        "extraction_time2_ms", ...
        "matching_time_ms", ...
        "figure_path" ...
    ]);
end
